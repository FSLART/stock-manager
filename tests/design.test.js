import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { mount, flushPromises } from '@vue/test-utils'
import App from '../frontend/src/App.vue'

let wrapper
const data = { can_edit: true, categories: [{ name: 'LEDs', props: ['cor'], image: false }], items: [{ id: 1, cat: 'LEDs', props: { cor: 'azul' }, qty: 3, image: '' }] }
beforeEach(() => {
  localStorage.clear()
  window.history.replaceState(null, '', '/')
  vi.stubGlobal('fetch', vi.fn(async url => ({ ok: true, json: async () => url === '/api/movements' ? { movements: [] } : structuredClone(data) })))
  HTMLDialogElement.prototype.showModal = function () { this.open = true }
  HTMLDialogElement.prototype.close = function () { this.open = false }
})
afterEach(() => { wrapper?.unmount(); vi.useRealTimers(); vi.unstubAllGlobals(); window.history.replaceState(null, '', '/') })
async function open(label) {
  await wrapper.findAll('.menu-link').find(button => button.text() === label).trigger('click')
  await flushPromises()
}
it('opens the reference home and navigates all six pages without losing backend inventory', async () => {
  wrapper = mount(App)
  await flushPromises()
  expect(wrapper.find('.home-summary').text()).toContain('3')
  for (const [label, title] of [['Inventário', 'Tudo em stock'], ['Simulação analógica', 'Simulação analógica'], ['Movimentos', 'Movimentos'], ['PCB e os seus BOMs', 'PCB e os seus BOMs'], ['Definições', 'Definições']]) {
    await open(label)
    expect(wrapper.find('h1').text()).toBe(title)
  }
  await open('Inventário')
  expect(wrapper.find('output').text()).toBe('3')
  expect(fetch.mock.calls.filter(([url]) => url === '/api/data')).toHaveLength(1)
})
it('imports a quoted BOM, persists it and reopens it after mounting again', async () => {
  wrapper = mount(App)
  await flushPromises()
  await open('PCB e os seus BOMs')
  await wrapper.find('.project-name-field input').setValue('Motor V1')
  const file = { name: 'motor.csv', text: async () => 'Reference,Value,Quantity,MPN,Description\r\n"R1,R2",10k,2,RC10K,"Resistor, precision"' }
  const input = wrapper.find('input[type=file]')
  Object.defineProperty(input.element, 'files', { configurable: true, value: [file] })
  await input.trigger('change')
  await flushPromises()
  await wrapper.find('.card-heading .primary-button').trigger('click')
  expect(wrapper.find('.bom-list').text()).toContain('RC10K')
  expect(wrapper.find('.bom-list').text()).toContain('Resistor, precision')
  expect(wrapper.find('.bom-quantity').text()).toBe('2')
  wrapper.unmount()
  wrapper = mount(App)
  await flushPromises()
  await wrapper.find('.saved-project-open').trigger('click')
  expect(wrapper.find('.pcb-project-detail h2').text()).toBe('Motor V1')
})
